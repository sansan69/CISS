/**
 * QR token generation and verification using Web Crypto API.
 * Works in both Node.js (18+) and browsers — no node:crypto import.
 */

const DEVELOPMENT_QR_SECRET = "ciss-qr-development-secret-only";

/**
 * The QR badge signature key. It must never fall back to a value an anonymous
 * caller can read (`NEXT_PUBLIC_*` is served by `/api/public/region-config`) or
 * to a literal committed to the repository.
 *
 * Server-only secrets already required for attendance token issuance are
 * accepted as fallbacks so a deployment that already works does not need a new
 * environment variable on day one. In production, if none is present, this
 * throws instead of silently signing badges with a public value.
 */
function getQrSecret(): string {
  const secret =
    process.env.CISS_QR_SECRET ||
    process.env.ATTENDANCE_VERIFICATION_SECRET ||
    process.env.UPLOAD_TOKEN_SECRET ||
    process.env.NEXTAUTH_SECRET;

  if (secret) return secret;

  if (process.env.NODE_ENV === "production") {
    throw new Error(
      "CISS_QR_SECRET (or ATTENDANCE_VERIFICATION_SECRET/UPLOAD_TOKEN_SECRET/NEXTAUTH_SECRET) must be configured in production.",
    );
  }

  return DEVELOPMENT_QR_SECRET;
}

/**
 * Verification-only key used by badges printed before the server-only secret
 * was introduced. It must never be used to sign new badges.
 */
const ALLOW_LEGACY_QR_SIGNATURES =
  process.env.ATTENDANCE_ALLOW_LEGACY_QR === "true";

function normalizeQrPhone(phoneNumber: string): string {
  const digits = String(phoneNumber ?? "").replace(/\D/g, "");
  return digits.length >= 10 ? digits.slice(-10) : digits;
}

function getLegacyQrSecret(): string {
  return (
    process.env.NEXT_PUBLIC_FIREBASE_API_KEY?.trim() ||
    "ciss-default-qr-secret"
  );
}

const keyCache = new Map<string, CryptoKey>();

async function getHmacKeyForSecret(secret: string): Promise<CryptoKey> {
  const cached = keyCache.get(secret);
  if (cached) return cached;
  const keyData = new TextEncoder().encode(secret);
  const key = await crypto.subtle.importKey(
    "raw",
    keyData,
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign", "verify"],
  );
  keyCache.set(secret, key);
  return key;
}

async function getHmacKey(): Promise<CryptoKey> {
  return getHmacKeyForSecret(getQrSecret());
}

/**
 * Generate a signed QR token for an employee.
 * The token proves the QR code was generated by CISS and hasn't been tampered with.
 */
async function signToken(
  secret: string,
  employeeId: string,
  phoneNumber: string,
): Promise<string> {
  const payload = `${employeeId}:${normalizeQrPhone(phoneNumber)}`;
  const key = await getHmacKeyForSecret(secret);
  const signature = await crypto.subtle.sign(
    "HMAC",
    key,
    new TextEncoder().encode(payload),
  );
  return btoa(String.fromCharCode(...new Uint8Array(signature)))
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=/g, "")
    .slice(0, 16);
}

export async function generateQrToken(
  employeeId: string,
  phoneNumber: string
): Promise<string> {
  return signToken(getQrSecret(), employeeId, phoneNumber);
}

/**
 * Verify that a QR token matches the expected employee data.
 */
export async function verifyQrToken(
  employeeId: string,
  phoneNumber: string,
  token: string
): Promise<boolean> {
  if (!token) return false;

  // New badges use the server-only secret; badges printed before that change
  // were signed with the public Firebase web API key. Verifying the legacy
  // form keeps already-distributed physical badges working during migration.
  const secrets: string[] = [];
  try {
    secrets.push(getQrSecret());
  } catch {
    // A deployment without the new secret can still verify legacy badges.
  }
  if (ALLOW_LEGACY_QR_SIGNATURES) {
    secrets.push(getLegacyQrSecret());
  }
  for (const secret of new Set(secrets)) {
    const expected = await signToken(secret, employeeId, phoneNumber);
    if (expected.length !== token.length) continue;
    let result = 0;
    for (let i = 0; i < expected.length; i++) {
      result |= expected.charCodeAt(i) ^ token.charCodeAt(i);
    }
    if (result === 0) return true;
  }
  return false;
}

/**
 * Build the full QR code content string with signed token.
 */
export async function buildQrContent(
  employeeId: string,
  fullName: string,
  phoneNumber: string
): Promise<string> {
  const normalizedPhone = normalizeQrPhone(phoneNumber);
  const token = await generateQrToken(employeeId, normalizedPhone);
  return `CISS-ATTENDANCE\nEmployee ID: ${employeeId}\nName: ${fullName}\nPhone: ${normalizedPhone}\nToken: ${token}`;
}

/**
 * Parse QR content and extract all fields including the token.
 */
export function parseQrContent(text: string): {
  employeeId: string | null;
  phoneNumber: string | null;
  name: string | null;
  token: string | null;
} {
  const normalized = text.replace(/\u0000/g, "").trim();
  if (!normalized) {
    return { employeeId: null, phoneNumber: null, name: null, token: null };
  }

  const employeeIdMatch = normalized.match(/Employee\s*ID\s*:\s*([^\n\r]+)/i);
  const phoneMatch = normalized.match(/Phone\s*:\s*([^\n\r]+)/i);
  const nameMatch = normalized.match(/Name\s*:\s*([^\n\r]+)/i);
  const tokenMatch = normalized.match(/Token\s*:\s*([^\n\r\s]+)/i);

  // Fallback: first line starting with CISS/
  const firstLine = normalized.split(/\r?\n/)[0]?.trim();
  const fallbackId =
    firstLine && /^CISS\//i.test(firstLine) ? firstLine : null;

  const phoneDigits = phoneMatch?.[1]?.replace(/\D/g, "").trim() ?? "";

  return {
    employeeId: employeeIdMatch?.[1]?.trim() ?? fallbackId,
    phoneNumber: phoneDigits.length >= 10 ? phoneDigits.slice(-10) : phoneDigits,
    name: nameMatch?.[1]?.trim() ?? null,
    token: tokenMatch?.[1]?.trim() ?? null,
  };
}
