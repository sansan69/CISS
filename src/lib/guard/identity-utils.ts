function formatDateOnly(date: Date): string {
  if (Number.isNaN(date.getTime())) {
    return "";
  }

  return date.toISOString().slice(0, 10);
}

function isDateOnlyString(value: string): boolean {
  return /^\d{4}-\d{2}-\d{2}$/.test(value);
}

function parseDateOnlyToUtcDays(value: string): number | null {
  if (!isDateOnlyString(value)) {
    return null;
  }

  const [year, month, day] = value.split("-").map(Number);
  if (!year || !month || !day) {
    return null;
  }

  return Math.floor(Date.UTC(year, month - 1, day) / 86_400_000);
}

type TimestampWithToDate = { toDate: () => Date };
type TimestampWithSeconds = { seconds?: number; _seconds?: number };
type TimestampLike = TimestampWithToDate | TimestampWithSeconds;

function isTimestampLike(value: unknown): value is TimestampLike {
  if (!value || typeof value !== "object") {
    return false;
  }

  return (
    typeof (value as { toDate?: unknown }).toDate === "function" ||
    typeof (value as { seconds?: unknown }).seconds === "number" ||
    typeof (value as { _seconds?: unknown })._seconds === "number"
  );
}

function hasToDate(value: TimestampLike): value is TimestampWithToDate {
  return "toDate" in value && typeof value.toDate === "function";
}

function hasSeconds(value: TimestampLike): value is TimestampWithSeconds {
  return "seconds" in value || "_seconds" in value;
}

export function normalizeGuardPhone(phone: string): string {
  return phone.replace(/\D/g, "");
}

/**
 * Parse guard phone input that may contain ordinary user-entered formatting.
 *
 * `normalizeGuardPhone` is retained for legacy stored-data comparisons. New
 * unauthenticated endpoints should use this parser first so letters and other
 * arbitrary characters are rejected instead of being silently discarded.
 */
export function parseGuardPhoneInput(value: unknown): string | null {
  if (typeof value !== "string") {
    return null;
  }

  const trimmed = value.trim();
  if (!trimmed || !/^\+?[\d\s()-]+$/.test(trimmed)) {
    return null;
  }

  let normalized = normalizeGuardPhone(trimmed);
  // Employee records use the national ten-digit mobile number. Accept common
  // Indian country-code entry without turning it into an unmatched identifier.
  if (normalized.length === 12 && normalized.startsWith("91")) {
    normalized = normalized.slice(2);
  } else if (normalized.length === 14 && normalized.startsWith("0091")) {
    normalized = normalized.slice(4);
  }

  return /^\d{8,15}$/.test(normalized) ? normalized : null;
}

const GUARD_EMPLOYEE_ID_MAX_LENGTH = 128;
const GUARD_EMPLOYEE_ID_PATTERN = /^[A-Za-z0-9/_-]+$/;

/**
 * Employee IDs generated by this project use letters, numbers, slashes, and
 * hyphens (for example, CISS/LNG/2026-27/001). Validate unauthenticated input
 * before it is used in a lookup or rate-limit fingerprint.
 */
export function parseGuardEmployeeIdInput(value: unknown): string | null {
  if (typeof value !== "string") {
    return null;
  }

  const trimmed = value.trim();
  if (
    !trimmed ||
    trimmed.length > GUARD_EMPLOYEE_ID_MAX_LENGTH ||
    !GUARD_EMPLOYEE_ID_PATTERN.test(trimmed)
  ) {
    return null;
  }

  return trimmed;
}

export function normalizeGuardDob(value: unknown): string {
  if (!value) {
    return "";
  }

  if (value instanceof Date) {
    return formatDateOnly(value);
  }

  if (typeof value === "string") {
    const trimmed = value.trim();
    if (!trimmed) {
      return "";
    }

    if (/^\d{4}-\d{2}-\d{2}$/.test(trimmed)) {
      return trimmed;
    }

    return formatDateOnly(new Date(trimmed));
  }

  if (isTimestampLike(value)) {
    if (hasToDate(value)) {
      return formatDateOnly(value.toDate());
    }

    if (!hasSeconds(value)) {
      return "";
    }

    const seconds =
      typeof value.seconds === "number"
        ? value.seconds
        : typeof value._seconds === "number"
          ? value._seconds
          : null;

    if (seconds !== null) {
      return formatDateOnly(new Date(seconds * 1000));
    }
  }

  return "";
}

function canHaveTimezoneShift(value: unknown): boolean {
  if (value instanceof Date || isTimestampLike(value)) {
    return true;
  }

  if (typeof value === "string") {
    const trimmed = value.trim();
    return Boolean(trimmed) && !isDateOnlyString(trimmed);
  }

  return false;
}

export function guardDobMatches(
  storedValue: unknown,
  inputValue: unknown,
): boolean {
  const storedDob = normalizeGuardDob(storedValue);
  const inputDob = normalizeGuardDob(inputValue);

  if (!storedDob || !inputDob) {
    return false;
  }

  if (storedDob === inputDob) {
    return true;
  }

  if (!canHaveTimezoneShift(storedValue)) {
    return false;
  }

  const storedDays = parseDateOnlyToUtcDays(storedDob);
  const inputDays = parseDateOnlyToUtcDays(inputDob);

  if (storedDays === null || inputDays === null) {
    return false;
  }

  return Math.abs(storedDays - inputDays) === 1;
}
